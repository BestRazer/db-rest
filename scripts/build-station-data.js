#!/usr/bin/env node

/**
 * Pre-bundle station data for Cloudflare Workers compatibility
 *
 * This script extracts data from db-stations and db-stations-autocomplete packages
 * and creates ES modules that can be bundled directly, avoiding the need for
 * createRequire() at runtime.
 */

import {readFileSync, writeFileSync, mkdirSync} from 'fs'
import {join, dirname} from 'path'
import {fileURLToPath} from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const outputDir = join(__dirname, '..', 'lib', 'bundled-data')

console.log('🏗️  Building pre-bundled station data for Cloudflare Workers...\n')

// Create output directory
try {
	mkdirSync(outputDir, {recursive: true})
	console.log(`✓ Created output directory: ${outputDir}`)
} catch (err) {
	console.error(`✗ Failed to create output directory:`, err.message)
	process.exit(1)
}

// Load db-stations data
console.log('\n📊 Processing db-stations data...')
let stationsData, fullStationsData
try {
	const stationsPath = join(__dirname, '..', 'node_modules', 'db-stations', 'data.json')
	const fullPath = join(__dirname, '..', 'node_modules', 'db-stations', 'full.json')

	stationsData = JSON.parse(readFileSync(stationsPath, 'utf8'))
	fullStationsData = JSON.parse(readFileSync(fullPath, 'utf8'))

	console.log(`✓ Loaded ${stationsData.length} stations from data.json`)
	console.log(`✓ Loaded ${fullStationsData.length} stations from full.json`)
} catch (err) {
	console.error(`✗ Failed to load db-stations data:`, err.message)
	process.exit(1)
}

// Load db-stations-autocomplete data
console.log('\n📊 Processing db-stations-autocomplete data...')
let tokens, scores, weights, nrOfTokens, originalIds
try {
	const basePath = join(__dirname, '..', 'node_modules', 'db-stations-autocomplete')

	tokens = JSON.parse(readFileSync(join(basePath, 'tokens.json'), 'utf8'))
	scores = JSON.parse(readFileSync(join(basePath, 'scores.json'), 'utf8'))
	weights = JSON.parse(readFileSync(join(basePath, 'weights.json'), 'utf8'))
	nrOfTokens = JSON.parse(readFileSync(join(basePath, 'nr-of-tokens.json'), 'utf8'))
	originalIds = JSON.parse(readFileSync(join(basePath, 'original-ids.json'), 'utf8'))

	console.log(`✓ Loaded autocomplete tokens (${tokens.length} entries)`)
	console.log(`✓ Loaded autocomplete scores`)
	console.log(`✓ Loaded autocomplete weights`)
	console.log(`✓ Loaded autocomplete nrOfTokens`)
	console.log(`✓ Loaded autocomplete originalIds`)
} catch (err) {
	console.error(`✗ Failed to load db-stations-autocomplete data:`, err.message)
	process.exit(1)
}

// Write db-stations data
console.log('\n📝 Writing pre-bundled modules...')
try {
	// Write stations data module
	const stationsModule = `// Auto-generated by scripts/build-station-data.js
// This file contains pre-bundled db-stations data for Cloudflare Workers compatibility

export const stationsData = ${JSON.stringify(stationsData, null, 0)};

export const fullStationsData = ${JSON.stringify(fullStationsData, null, 0)};
`
	writeFileSync(join(outputDir, 'db-stations.js'), stationsModule, 'utf8')
	console.log(`✓ Wrote lib/bundled-data/db-stations.js`)

	// Write autocomplete data module
	const autocompleteModule = `// Auto-generated by scripts/build-station-data.js
// This file contains pre-bundled db-stations-autocomplete data for Cloudflare Workers compatibility

export const tokens = ${JSON.stringify(tokens, null, 0)};

export const scores = ${JSON.stringify(scores, null, 0)};

export const weights = ${JSON.stringify(weights, null, 0)};

export const nrOfTokens = ${JSON.stringify(nrOfTokens, null, 0)};

export const originalIds = ${JSON.stringify(originalIds, null, 0)};

export const autocompleteIndex = {
	tokens,
	scores,
	weights,
	nrOfTokens,
	originalIds,
};
`
	writeFileSync(join(outputDir, 'db-stations-autocomplete.js'), autocompleteModule, 'utf8')
	console.log(`✓ Wrote lib/bundled-data/db-stations-autocomplete.js`)

} catch (err) {
	console.error(`✗ Failed to write modules:`, err.message)
	process.exit(1)
}

// Calculate sizes
const stationsSize = (JSON.stringify(stationsData).length / 1024).toFixed(2)
const fullSize = (JSON.stringify(fullStationsData).length / 1024).toFixed(2)
const autocompleteSize = (JSON.stringify({tokens, scores, weights, nrOfTokens, originalIds}).length / 1024).toFixed(2)

console.log('\n✅ Build complete!')
console.log(`\n📦 Bundle sizes:`)
console.log(`   - db-stations (data.json): ${stationsSize} KB`)
console.log(`   - db-stations (full.json): ${fullSize} KB`)
console.log(`   - db-stations-autocomplete: ${autocompleteSize} KB`)
console.log(`   - Total: ${(parseFloat(stationsSize) + parseFloat(fullSize) + parseFloat(autocompleteSize)).toFixed(2)} KB`)
console.log(`\n⚠️  Note: These modules will be included in your worker bundle.`)
console.log(`   Make sure your total bundle stays under Cloudflare's 1MB limit.`)
